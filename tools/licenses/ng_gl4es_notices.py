#!/usr/bin/env python3
"""Collects the license and copyright notices from NG-GL4ES's pinned source tree.

Usage:
    python3 ng_gl4es_notices.py <ng-gl4es-source-dir> <output-file> <expected-commit>

Every file under src/ and include/ that carries a copyright or license marker is read. The comment block that
holds each marker is copied verbatim. Identical blocks are written once, with the list of files they came from.
The script exits with an error if a marker is found where no comment block can be identified, so a notice
can never be skipped silently.

The output is deterministic: files are sorted, and blocks are numbered in order of first appearance.
"""

import hashlib
import os
import sys

MARKERS = (
    "Copyright",
    "copyright",
    "SPDX-License-Identifier",
    "Permission is hereby granted",
    "Redistribution and use",
    "Licensed under",
    "GNU General Public",
    "GNU Lesser General Public",
    "Apache License",
    "THIS SOFTWARE IS PROVIDED",
)

SOURCE_EXTENSIONS = (".h", ".hh", ".hpp", ".hxx", ".c", ".cc", ".cpp", ".cxx", ".inl", ".def")


def has_marker(line):
    return any(marker in line for marker in MARKERS)


def block_for_line(lines, index):
    """Returns (start, end) line indexes of the comment block that contains line `index`, or None."""
    stripped = lines[index].strip()
    if stripped.startswith("//"):
        start = index
        while start > 0 and lines[start - 1].strip().startswith("//"):
            start -= 1
        end = index
        while end + 1 < len(lines) and lines[end + 1].strip().startswith("//"):
            end += 1
        return start, end

    # Block comment: walk up to the opening "/*" with no closing "*/" in between.
    start = None
    for j in range(index, -1, -1):
        if "*/" in lines[j] and j != index:
            return None
        if "/*" in lines[j]:
            start = j
            break
    if start is None:
        return None
    for j in range(index, len(lines)):
        if "*/" in lines[j]:
            return start, j
    return None


def collect(root):
    """Returns {block_text: set(relative paths)} for every notice-bearing source file, plus unresolved entries."""
    blocks = {}
    unresolved = []
    for subdir in ("src", "include"):
        base = os.path.join(root, subdir)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            for name in sorted(filenames):
                if not name.endswith(SOURCE_EXTENSIONS):
                    continue
                path = os.path.join(dirpath, name)
                rel = os.path.relpath(path, root).replace(os.sep, "/")
                with open(path, encoding="latin-1") as handle:
                    lines = handle.read().split("\n")
                seen_ranges = []
                for index, line in enumerate(lines):
                    if not has_marker(line):
                        continue
                    if any(start <= index <= end for start, end in seen_ranges):
                        continue
                    found = block_for_line(lines, index)
                    if found is None:
                        unresolved.append(f"{rel}:{index + 1}")
                        continue
                    start, end = found
                    seen_ranges.append((start, end))
                    text = "\n".join(lines[start:end + 1])
                    blocks.setdefault(text, set()).add(rel)
    return blocks, unresolved


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    root, output, commit = sys.argv[1], sys.argv[2], sys.argv[3]
    blocks, unresolved = collect(root)
    if unresolved:
        print("Notice markers with no identifiable comment block:")
        for entry in unresolved:
            print("  " + entry)
        return 1

    out = []
    out.append("Third-party notices bundled with NG-GL4ES")
    out.append(f"NG-GL4ES source commit: {commit}")
    out.append("Generated by tools/licenses/ng_gl4es_notices.py from the pinned source. Each notice is copied")
    out.append("verbatim from the files listed under it. The full license texts for glslang and SPIRV-Cross are in")
    out.append("their own files, and the Khronos and Apache-2.0 texts are in Khronos-Apache-2.0-notices.txt.")
    out.append("")
    ordered = sorted(blocks.items(), key=lambda item: sorted(item[1])[0])
    for number, (text, files) in enumerate(ordered, start=1):
        out.append(f"===== Notice {number} of {len(ordered)}")
        out.append("Files:")
        for rel in sorted(files):
            out.append(f"  {rel}")
        out.append("Text:")
        out.append(text)
        out.append("")
    body = "\n".join(out)
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(body)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    file_count = len({rel for files in blocks.values() for rel in files})
    print(f"Wrote {output}: {len(ordered)} unique notices from {file_count} files, sha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
